source(here("0_Parameters.R"))

# Diseases considered
dis_vec <- c("mort", "cancer", "cvd", "diab2", "dem", "dep")



################################################################################################################################
#                                                    4. DATA PREPARATION                                                       #
################################################################################################################################

##############################################################
#                     WALKERS DATASET                        #
##############################################################

# Initialization
emp_long <- emp_long %>% 
  # Round the number of steps to the nearest ten and baseline at 2000
  mutate(step = pmin(12000, round(step_commute / 10) * 10+ 2000))



# EMP Dataset per disease and bound
walkers_list <- list()

for(dis in dis_vec) {
    dis_walkers <- emp_long %>% 
    filter(disease == dis)
  
  walkers_list[[dis]] <- dis_walkers
}



################################################################################################################################
#                                                 5. HEALTH IMPACT ASSESSMENT                                                  #
################################################################################################################################
HIA_list <- calc_HIA_replicate(walkers_list, 
                               NULL,
                               reduction_risk_central_table,
                               dw_table,
                               dis_vec,
                               vsl)


burden <- burden_prevented_replicate(HIA_list, dis_vec, NULL)
