# Walkers dataset
emp_long <- import(here("data_clean", "EMP_dis_walkers.xlsx"))


# RR by step, simulated dose-response relationships
reduction_risk_central_table <- import(here("data_clean", "Diseases", "DRF", "reduction_risk_central_table.xlsx"))


